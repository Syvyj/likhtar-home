package com.likhtar.home.core.designsystem

import androidx.compose.ui.BiasAlignment

/**
 * Як кадр стоїть у зоні іншої форми: по центру ліво-право, зі зсувом до верху.
 *
 * Дві осі — дві різні відповіді, і вони одна одній не суперечать. По горизонталі центр:
 * кадр не повинен тулитись до краю, бо тоді композиція з'їжджає тим сильніше, чим ширше
 * джерело (банери Телепорталу 2.6:1, постери 1+1 4:3, кадри TMDB 16:9).
 *
 * По вертикалі — верх, і це не стиль, а властивість матеріалу: у постерах і кадрах
 * обличчя лежать у верхній третині, тож центрована обрізка ріже голови. Зсув −0.3
 * зберігає їх і при цьому не задирає кадр так, щоб знизу лишалась порожня смуга.
 *
 * Спільна константа, а не три однакові на трьох екранах: правило одне для карток рядів,
 * шапки розділу й сторінки матеріалу.
 */
val FaceSafeCrop = BiasAlignment(horizontalBias = 0f, verticalBias = -0.3f)
