package com.likhtar.home.core.designsystem

import androidx.compose.ui.unit.dp

/**
 * Розміри LIKHTAR.
 *
 * Прототип зверстано в пікселях на канві 1920×1080. Android TV 1080p повідомляє щільність 2.0,
 * тобто робоча канва — 960×540 dp. Тому кожне значення тут = піксель прототипу / 2,
 * а 4K (3840×2160) отримується автоматично, бо все виражене в dp.
 */
object LikhtarDimens {
    /** Горизонтальні поля екрана: --pad прототипів, 96 px → 48 dp. */
    val ScreenPadding = 48.dp

    /** Висота верхнього меню: 96px → 48dp. */
    val TopMenuHeight = 40.dp
    val TopMenuGap = 14.dp

    /**
     * Наскільки росте під фокусом картка-кадр у ряду: Кінозал, серії, «Відкрити всі».
     *
     * Одне число на всі такі ряди: щойно воно розійшлось (1.10 в Кінозалі проти 1.06 у
     * серіях), різниця почала читатись як інша анімація, хоча tween у них спільний.
     * Вертикальні постери мають власний, менший зріст — на висоті 225dp десять відсотків
     * вилізають на сусідній ряд.
     */
    const val CardFocusScale = 1.07f

    /** Проміжок рейки між слотами карток; самі картки в Кінозалі мають ще по 7 dp полів. */
    val RailGap = 14.dp

    /**
     * Видима відстань між картками — одна на всі ряди й сітки: Кінозал 7 + 14 + 7 (поля
     * картки й проміжок рейки), сторінки сервісів і добірки — 28 одним проміжком (було 24, під більші картки). Менше не
     * можна: фокус збільшує картку на 10 %, ~13 dp з кожного боку, і сусіди накладались.
     */
    val CardGap = 28.dp

    /** Поля слота картки в рядах і сітках: запас під збільшення у фокусі (див. [cardSlot]). */
    val CardSlotX = 2.dp
    val CardSlotY = 8.dp
    val RailTitleGap = 6.dp
    val SectionGap = 14.dp

    /** Поля рядка списку (Налаштування, розділи, системні): одні на всі (було 12 × 8 / 9). */
    val ListRowX = 12.dp
    val ListRowY = 10.dp

    /** Від верхнього меню до заголовка сторінки ([PageHeader]). */
    val PageHeaderTop = 14.dp

    /**
     * Плитка навігації на Головній.
     *
     * 62dp було під плитку з крапкою-акцентом і назвою в один рядок. Плитка редизайну
     * несе значок над підписом, і на старій висоті підпис зрізало по нижньому краю.
     */
    val NavTileHeight = 74.dp

    /** Картка каналу: 218×86px → 109×43dp. */
    val ChannelCardWidth = 109.dp
    val ChannelCardHeight = 43.dp

    /** Улюблений канал у ТВ Ефірі: 262×96px → 131×48dp. */
    val FavoriteChannelWidth = 131.dp
    val FavoriteChannelHeight = 48.dp

    /**
     * Плитка застосунку 16:9. У макеті 232×132 — це піксели канви 1920, тобто 116×66dp:
     * у dp вона б не влізла й утричі (960dp на весь екран проти 6 плиток по 232).
     */
    val AppTileWidth = 116.dp
    val AppTileIconHeight = 66.dp

    /** Постер 16:9 у Кінозалі: 260×146px → 130×73dp. */
    val PosterWidth = 130.dp
    val PosterHeight = 73.dp

    /** Слот телепрограми: висота 82px → 41dp. */
    val GuideSlotHeight = 41.dp
    val GuideChannelColumnWidth = 120.dp

    /** Постійна рамка картки: 1px прототипу. */
    val BorderWidth = 1.dp

    /**
     * Фокус-кільце малюється зовні картки: 4px прототипу → 2dp, з відступом у товщину рамки,
     * плюс ширший приглушений ореол замість тіні (на тлі 0A0D0F тінь не видно).
     */
    val FocusRingWidth = 2.dp
    val FocusRingGap = 2.dp
    val FocusHaloWidth = 5.dp
    val FocusHaloGap = 5.dp

    /** Скільки місця треба лишити навколо картки, щоб кільце й ореол не зрізало. */
    val FocusBleed = FocusHaloGap + FocusHaloWidth

    // Шкала скруглень — одна на весь лаунчер (було 15 різних значень від 2 до 24 dp).
    /** Піктограми, смужки прогресу, дрібні позначки. */
    val CornerTiny = 4.dp
    /** Мітки й плашки (UA, якість, підпис картки, мета-чипи). */
    val CornerSmall = 6.dp
    /** Картки рядів і сіток. */
    val CornerMedium = 8.dp
    /** Панелі, діалоги, блоки «Чи варто?». */
    val CornerLarge = 12.dp
    /** Плитки Головної й застосунків, погода, великі банери. */
    val CornerXLarge = 16.dp
    val CornerPill = 999.dp
}
